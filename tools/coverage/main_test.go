func TestGeneratedFile(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	handwritten := filepath.Join(dir, "hand.go")
	generated := filepath.Join(dir, "generated.go")

	err := os.WriteFile(handwritten, []byte("package sample\n"), 0600)
	if err != nil {
		t.Fatal(err)
	}

	err = os.WriteFile(generated, []byte("// Code generated by a tool. DO NOT EDIT.\npackage sample\n"), 0600)
	if err != nil {
		t.Fatal(err)
	}

	for filename, want := range map[string]bool{handwritten: false, generated: true, "models.gen.go": true} {
		got, err := generatedFile(filename)
		if err != nil {
			t.Fatal(err)
		}

		if got != want {
			t.Errorf("generatedFile(%q) = %v, want %v", filename, got, want)
		}
	}
}

func TestReportRejectsCoveragePathOutsidePackageRoot(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "go.mod"), []byte("module example.com/test\n"), 0600); err != nil {
		t.Fatal(err)
	}

	profile := "mode: set\nexample.com/test/pkg/../../outside.go:1.1,1.2 1 1\n"
	if err := os.WriteFile(filepath.Join(dir, "coverage.out"), []byte(profile), 0600); err != nil {
		t.Fatal(err)
	}

	err := reportInDirectory(dir, "coverage.out", 0, true, "")
	if !errors.Is(err, errInvalidCoveragePath) {
		t.Fatalf("reportInDirectory() error = %v, want path escape error", err)
	}
}

//nolint:cyclop,funlen // Each subtest asserts a separate report classification and weighted summary property.
func TestReportUsesStatementWeightsAndExcludesGeneratedFiles(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()

	if err := os.MkdirAll(filepath.Join(dir, "pkg/sample"), 0700); err != nil {
		t.Fatal(err)
	}

	if err := os.MkdirAll(filepath.Join(dir, "pkg/testing"), 0700); err != nil {
		t.Fatal(err)
	}

	for name, contents := range map[string]string{
		"go.mod":                   "module example.com/test\n",
		"pkg/sample/client.go":     "package sample\n",
		"pkg/sample/models.gen.go": "// Code generated by a tool. DO NOT EDIT.\npackage sample\n",
		"pkg/testing/helper.go":    "package testing\n",
	} {
		err := os.WriteFile(filepath.Join(dir, name), []byte(contents), 0600)
		if err != nil {
			t.Fatal(err)
		}
	}

	profile := strings.Join([]string{
		"mode: set",
		"example.com/test/pkg/sample/client.go:1.1,1.2 4 1",
		"example.com/test/pkg/sample/client.go:2.1,2.2 6 0",
		"example.com/test/pkg/sample/models.gen.go:1.1,1.2 100 0",
		"example.com/test/pkg/testing/helper.go:1.1,1.2 100 0",
	}, "\n") + "\n"
	if err := os.WriteFile(filepath.Join(dir, "coverage.out"), []byte(profile), 0600); err != nil {
		t.Fatal(err)
	}

	if err := reportInDirectory(dir, "coverage.out", 40, false, "filtered.out"); err != nil {
		t.Fatalf("40%% should pass: %v", err)
	}

	// #nosec G304 -- dir is owned by this test's temporary directory.
	filtered, err := os.ReadFile(filepath.Join(dir, "filtered.out"))
	if err != nil {
		t.Fatal(err)
	}

	if strings.Contains(string(filtered), "models.gen.go") || strings.Contains(string(filtered), "helper.go") || !strings.Contains(string(filtered), "client.go") {
		t.Fatalf("filtered profile has wrong records: %s", filtered)
	}

	if err := reportInDirectory(dir, "coverage.out", 41, false, ""); err == nil {
		t.Fatal("41% should fail")
	}
	// A -coverpkg profile can repeat each block for several package test
	// binaries. Count the block once and merge coverage from all copies.
	profile += "example.com/test/pkg/sample/client.go:1.1,1.2 4 0\n"

	profile += "example.com/test/pkg/sample/client.go:2.1,2.2 6 1\n"

	if err := os.WriteFile(filepath.Join(dir, "coverage.out"), []byte(profile), 0600); err != nil {
		t.Fatal(err)
	}

	if err := reportInDirectory(dir, "coverage.out", 100, false, "filtered.out"); err != nil {
		t.Fatalf("duplicate blocks should merge to 100%%: %v", err)
	}

	// #nosec G304 -- dir is owned by this test's temporary directory.
	filtered, err = os.ReadFile(filepath.Join(dir, "filtered.out"))
	if err != nil {
		t.Fatal(err)
	}

	if strings.Count(string(filtered), "client.go:") != 2 {
		t.Fatalf("filtered profile did not deduplicate blocks: %s", filtered)
	}
}
